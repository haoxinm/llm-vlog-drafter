def digest(p):
    return hashlib.sha256(p.read_bytes()).hexdigest()


def test_native_state_judges_like_the_compatibility_report(built):
    adapter, spec, proj, out = built
    x = out / "timeline.xml"
    assert RB.native_state(x, spec)[0] == "missing"
    x.write_text("not xml", encoding="utf-8")
    assert RB.native_state(x, spec)[0] == "unreadable"
    # keyframes and the fit scale are part of "carries the timeline"
    x.write_text(xml_for_spec(spec), encoding="utf-8")
    assert RB.native_state(x, spec) == ("ok", [])
    x.write_text(xml_for_spec(spec, mutate=lambda d: d["markers"].clear()), encoding="utf-8")
    state, issues = RB.native_state(x, spec)
    assert state == "lossy" and "marker" in issues[0]
    assert RB.native_state(x, spec, listed_error="export failed")[0] == "missing"


def test_a_good_native_export_is_never_touched(built):
    adapter, spec, proj, out = built
    x = out / "timeline.xml"
    x.write_text(xml_for_spec(spec), encoding="utf-8")
    before = digest(x)
    rec = RB.run_fallback(adapter, spec, ["fcp7_xml", "otio"], out, proj, mode="auto")
    assert rec["status"] == "not_needed" and digest(x) == before
    assert sorted(p.name for p in out.iterdir()) == ["timeline.xml"]


def test_missing_native_export_gets_a_verified_readback_file(built):
    adapter, spec, proj, out = built
    rec = RB.run_fallback(adapter, spec, ["fcp7_xml"], out, proj, mode="auto", listed_error="FilmCraft could not export")
    assert rec["status"] == "generated" and rec["label"] == "generated from FilmCraft read-back" and rec["kept_native"] is None
    x = out / "timeline.xml"
    assert digest(x) == rec["sha256"] and "generated by trip-vlog from the timeline read back" in x.read_text(encoding="utf-8")
    # the generated file is parsed again and equals the timeline that was sent to FilmCraft; keyframes are the one thing it cannot carry
    rt = X.compare_timeline_xml(parse_fcp7_xml(x), X.expected_from_spec(spec), keyframes_carried=False)
    assert rt.ok, [str(m) for m in rt.mismatches]
    tl = parse_fcp7_xml(x)
    assert any(c.scale and abs(c.scale - 56.25) < 1e-6 for c in tl.clips) and all(not c.gain_keys for c in tl.clips)
    assert rec["crosscheck"]["ok"] and any("volume keyframe" in n for n in rec["not_carried"])
    assert json.loads((out / RB.REPORT_NAME).read_text(encoding="utf-8"))["status"] == "generated"
    assert not (out / RB.CANDIDATE_NAME).exists()
    again = RB.run_fallback(adapter, spec, ["fcp7_xml"], out, proj, mode="auto", listed_error="FilmCraft could not export")
    assert again["status"] == "generated" and digest(x) == rec["sha256"]       # idempotent


def test_lossy_native_export_is_kept_beside_the_generated_one(built):
    adapter, spec, proj, out = built
    x = out / "timeline.xml"
    x.write_text(xml_for_spec(spec, mutate=lambda d: d["markers"].clear()), encoding="utf-8")
    lossy = digest(x)
    rec = RB.run_fallback(adapter, spec, ["fcp7_xml"], out, proj, mode="auto")
    assert rec["status"] == "generated" and rec["native"]["state"] == "lossy" and rec["kept_native"] == "timeline.native.xml"
    assert digest(out / "timeline.native.xml") == lossy and digest(x) == rec["sha256"] != lossy


def test_a_readback_that_does_not_match_is_discarded_and_reported(built):
    adapter, spec, proj, out = built
    other = replace(spec, markers=(MarkerSpec(100, "Elsewhere", ""),))        # what the caller expects is not what FilmCraft holds
    x = out / "timeline.xml"
    x.write_text(xml_for_spec(other, mutate=lambda d: d["markers"].clear()), encoding="utf-8")
    before = digest(x)
    rec = RB.run_fallback(adapter, other, ["fcp7_xml"], out, proj, mode="auto")
    assert rec["status"] == "failed" and "does not round-trip" in rec["reason"] and rec["roundtrip"]
    assert rec["crosscheck"]["count"] >= 1                                   # the plan-versus-readback diff is reported, not papered over
    assert digest(x) == before and not (out / RB.CANDIDATE_NAME).exists() and not (out / "timeline.native.xml").exists()


def test_switched_off_or_not_requested(built):
    adapter, spec, proj, out = built
    assert RB.run_fallback(adapter, spec, ["fcp7_xml"], out, proj, mode="off")["status"] == "off"
    assert RB.run_fallback(adapter, spec, ["otio"], out, proj, mode="auto")["status"] == "not_requested"
    assert list(out.iterdir()) == []


def test_stale_provenance_is_set_aside_when_the_native_export_is_good_again(built):
    adapter, spec, proj, out = built
    RB.run_fallback(adapter, spec, ["fcp7_xml"], out, proj, mode="auto", listed_error="x")
    (out / "timeline.xml").write_text(xml_for_spec(spec), encoding="utf-8")        # next run: FilmCraft exported fine
    assert RB.run_fallback(adapter, spec, ["fcp7_xml"], out, proj, mode="auto")["status"] == "not_needed"
    assert not (out / RB.REPORT_NAME).exists() and (out / (RB.REPORT_NAME + ".stale")).is_file()


def test_roundtrip_compares_scale_and_ducking_keyframes(built):
    adapter, spec, proj, out = built
    exact = parse_fcp7_xml(xml_for_spec(spec))
    assert X.compare_timeline_xml(exact, X.expected_from_spec(spec)).ok
    no_keys = parse_fcp7_xml(xml_for_spec(replace(spec, placements=tuple(replace(p, gain_keys=()) for p in spec.placements))))
    rt = X.compare_timeline_xml(no_keys, X.expected_from_spec(spec))
    assert [m.feature for m in rt.mismatches] == [X.F_DUCKING]
    assert X.compare_timeline_xml(no_keys, X.expected_from_spec(spec), keyframes_carried=False).ok
    wrong_scale = parse_fcp7_xml(xml_for_spec(spec, mutate=lambda d: [i.__setitem__("scale", 100.0) for i in d["items"] if i["scale"]]))
    assert [m.feature for m in X.compare_timeline_xml(wrong_scale, X.expected_from_spec(spec)).mismatches] == [X.F_FRAMING]
