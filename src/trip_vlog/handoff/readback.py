"""FCP7 XML generated from the timeline READ BACK from FilmCraft (DESIGN §15.3).

Used only when FilmCraft's own FCP7 XML export is missing or does not carry the timeline (a mismatch against what was sent to FilmCraft,
found with the same comparison the compatibility report uses). It never replaces a good native export.

The source of truth is FilmCraft's own state, read through its inspection interface in a freshly opened process (``SequenceSnapshot`` and
``ProjectSnapshot``), never the edit plan. The plan only enters afterwards, as the cross-check: the read-back is compared with the
resolved plan (``verify_against_spec``) and the generated file is parsed again and compared with the timeline it must hold
(``compare_timeline_xml``). A generated file that does not round-trip exactly is not used.

What the read-back can carry: sequence rate, size and duration; clip order, record and source in/out, media paths (V and A tracks, stills,
overlays); centred cross dissolves; markers; constant clip gain; the Motion scale of video items; title clips (name and text only, FilmCraft
names a text clip after its text; font, size and position are not part of the read-back). What it cannot: effects other than those, and
keyframe values (the read-back reports how many keyframes a parameter has, not their times and values), so ducking envelopes are not in it.
The structure follows FilmCraft's own FCP7 XML export (xmeml version 4) so that what Resolve accepted from that export is what it gets here.
"""

from __future__ import annotations

import math
import urllib.parse
import xml.etree.ElementTree as ET
from dataclasses import dataclass, field
from fractions import Fraction
from pathlib import Path
from typing import Any, Mapping

from trip_vlog.filmcraft.inspect import ClipSnapshot, ProjectSnapshot, SequenceSnapshot
from trip_vlog.filmcraft.timebase import TICKS_PER_SECOND
from trip_vlog.handoff.xml_roundtrip import centred_transition_span

GENERATOR_NOTE = "generated by trip-vlog from the timeline read back from FilmCraft (DESIGN 15.3); FilmCraft's own export was not used"


class ReadbackError(ValueError):
    """The read-back timeline cannot be written as FCP7 XML without inventing something."""


@dataclass
class ReadbackXml:
    text: str
    clips: int = 0
    not_carried: list[str] = field(default_factory=list)      # features present in FilmCraft that this file does not hold


def pathurl(path: str) -> str:
    """``file://localhost/...`` URL as FilmCraft writes it (``file://localhost/C:/dir/x.mp4`` for a drive path)."""
    posix = str(path).replace("\\", "/")
    if not posix.startswith("/"):
        posix = "/" + posix
    return "file://localhost" + urllib.parse.quote(posix, safe="/:")


def _rate(parent: ET.Element, fps: Fraction) -> None:
    ntsc = fps.denominator == 1001
    if not ntsc and fps.denominator != 1:
        raise ReadbackError(f"frame rate {fps} cannot be written as an FCP7 XML rate")
    r = ET.SubElement(parent, "rate")
    ET.SubElement(r, "timebase").text = str(math.ceil(fps) if ntsc else int(fps))
    ET.SubElement(r, "ntsc").text = "TRUE" if ntsc else "FALSE"


def _text(parent: ET.Element, tag: str, value: Any) -> ET.Element:
    e = ET.SubElement(parent, tag)
    e.text = str(value)
    return e


def _frames(ticks: int, fps: Fraction) -> int:
    return int(round(Fraction(ticks) * fps / TICKS_PER_SECOND))


def _param(f: ET.Element, pid: str, name: str, value: Any = None, **extra: Any) -> ET.Element:
    p = ET.SubElement(f, "parameter")
    _text(p, "parameterid", pid)
    _text(p, "name", name)
    for k, v in extra.items():
        _text(p, k, v)
    if value is not None:
        _text(p, "value", value)
    return p


def _filter(item: ET.Element, name: str, effect_id: str, category: str, kind: str, media: str) -> ET.Element:
    f = ET.SubElement(ET.SubElement(item, "filter"), "effect")
    _text(f, "name", name)
    _text(f, "effectid", effect_id)
    _text(f, "effectcategory", category)
    _text(f, "effecttype", kind)
    _text(f, "mediatype", media)
    return f


def build_readback_xml(snap: SequenceSnapshot, project: ProjectSnapshot) -> ReadbackXml:
    fps = snap.fps
    media = project.media_by_item()
    not_carried: list[str] = []
    root = ET.Element("xmeml", version="4")
    seq = ET.SubElement(root, "sequence", id="sequence-1")
    _text(seq, "name", snap.name)
    _text(seq, "duration", snap.duration_frames)
    _rate(seq, fps)
    tc = ET.SubElement(seq, "timecode")
    _rate(tc, fps)
    _text(tc, "string", "00:00:00:00")
    _text(tc, "frame", 0)
    _text(tc, "displayformat", "NDF")
    med = ET.SubElement(seq, "media")
    vid, aud = ET.SubElement(med, "video"), ET.SubElement(med, "audio")
    sc = ET.SubElement(ET.SubElement(vid, "format"), "samplecharacteristics")
    _rate(sc, fps)
    _text(sc, "width", snap.width)
    _text(sc, "height", snap.height)
    _text(sc, "anamorphic", "FALSE")
    _text(sc, "pixelaspectratio", "square")
    _text(sc, "fielddominance", "none")
    asc = ET.SubElement(ET.SubElement(aud, "format"), "samplecharacteristics")
    _text(asc, "depth", 16)
    _text(asc, "samplerate", 48000)

    # ids first, so links can name the other half of a pair
    ids: dict[int, str] = {}
    n = 0
    for kind in ("video", "audio"):
        for t in snap.tracks:
            if t.kind == kind:
                for c in t.clips:
                    n += 1
                    ids[c.clip_id] = f"clipitem-{n}"
    position: dict[int, tuple[str, int, int]] = {}      # clip id -> (kind, 1-based track, 1-based index)
    for t in snap.tracks:
        for i, c in enumerate(t.clips, 1):
            position[c.clip_id] = (t.kind, int(t.name[1:]), i)
    file_ids: dict[int, str] = {}
    masters: dict[int, str] = {}
    n_clips = 0

    def media_path(c: ClipSnapshot) -> str | None:
        row = media.get(c.item) if c.item is not None else None
        return row.path if row is not None and row.path else None

    for kind, parent in (("video", vid), ("audio", aud)):
        for t in [t for t in snap.tracks if t.kind == kind]:
            track = ET.SubElement(parent, "track")
            incoming = {tr.to_clip: tr for tr in t.transitions if tr.to_clip is not None}
            for c in t.clips:
                tr = incoming.get(c.clip_id)
                if tr is not None and kind == "video":
                    if tr.align not in (None, "center"):
                        not_carried.append(f"{t.name}: a '{tr.align}' aligned {tr.effect} (only centred dissolves are written)")
                    elif tr.effect != "cross_dissolve":
                        not_carried.append(f"{t.name}: a '{tr.effect}' transition (only the cross dissolve is written)")
                    else:
                        el = ET.SubElement(track, "transitionitem")
                        _rate(el, fps)
                        frames = _frames(tr.duration_ticks, fps)
                        s, e = centred_transition_span(c.start_frame, frames)
                        _text(el, "start", s)
                        _text(el, "end", e)
                        _text(el, "alignment", "center")
                        ef = ET.SubElement(el, "effect")
                        _text(ef, "name", "Cross Dissolve")
                        _text(ef, "effectid", "Cross Dissolve")
                        _text(ef, "effectcategory", "Dissolve")
                        _text(ef, "effecttype", "transition")
                        _text(ef, "mediatype", "video")
                elif tr is not None:
                    not_carried.append(f"{t.name}: an audio transition ({tr.effect}) is not written")
                path = media_path(c)
                is_title = kind == "video" and path is None
                it = ET.SubElement(track, "clipitem", id=ids[c.clip_id])
                if c.item is not None and not is_title:
                    _text(it, "masterclipid", masters.setdefault(c.item, f"masterclip-{len(masters) + 1}"))
                _text(it, "name", c.name)
                _text(it, "enabled", "TRUE" if c.enabled else "FALSE")
                pitem = project.item(c.item) if c.item is not None else None
                src_dur = _frames(pitem.duration_ticks, fps) if pitem is not None and pitem.duration_ticks else max(c.duration_frames, _frames(c.source_out_ticks, fps))
                _text(it, "duration", max(src_dur, _frames(c.source_out_ticks, fps)))
                _rate(it, fps)
                _text(it, "start", c.start_frame)
                _text(it, "end", c.end_frame)
                _text(it, "in", _frames(c.source_in_ticks, fps))
                _text(it, "out", _frames(c.source_out_ticks, fps))
                _text(it, "pproTicksIn", c.source_in_ticks)
                _text(it, "pproTicksOut", c.source_out_ticks)
                if path is not None:
                    fid = file_ids.get(c.item)
                    if fid is None:
                        fid = file_ids[c.item] = f"file-{len(file_ids) + 1}"
                        fe = ET.SubElement(it, "file", id=fid)
                        _text(fe, "name", Path(path.replace("\\", "/")).name)
                        _text(fe, "pathurl", pathurl(path))
                        _rate(fe, fps)
                        _text(fe, "duration", src_dur)
                    else:
                        ET.SubElement(it, "file", id=fid)
                if kind == "audio":
                    st = ET.SubElement(it, "sourcetrack")
                    _text(st, "mediatype", "audio")
                    _text(st, "trackindex", int(t.name[1:]))
                if kind == "video":
                    if c.scale is not None and not is_title:
                        m = _filter(it, "Basic Motion", "basic", "motion", "motion", "video")
                        _param(m, "scale", "Scale", c.scale, valuemin=0, valuemax=1000)
                        _param(m, "rotation", "Rotation", 0, valuemin=-8640, valuemax=8640)
                        for pid, nm in (("center", "Center"), ("centerOffset", "Anchor Point")):
                            p = _param(m, pid, nm)
                            v = ET.SubElement(p, "value")
                            _text(v, "horiz", 0)
                            _text(v, "vert", 0)
                    if is_title:
                        tx = _filter(it, "Text", "graphic_text", "Filter", "filter", "video")
                        _param(tx, "text", "Source Text", c.name)
                elif abs(c.gain_db) > 1e-9:
                    lv = _filter(it, "Audio Levels", "audiolevels", "audiolevels", "audiolevels", "audio")
                    _param(lv, "level", "Level", repr(10 ** (c.gain_db / 20)), valuemin=0, valuemax=3.98109)
                if kind == "audio" and c.volume_keyframes:
                    not_carried.append(f"{t.name} {c.name}: {c.volume_keyframes} volume keyframe(s) (their times and values are not part of the read-back)")
                pair = sorted((c.clip_id, c.link), key=lambda cid: position[cid][0] != "video") if (c.link in ids and not is_title) else []
                for other in pair:
                    k, ti, ci = position[other]
                    lk = ET.SubElement(it, "link")
                    _text(lk, "linkclipref", ids[other])
                    _text(lk, "mediatype", k)
                    _text(lk, "trackindex", ti)
                    _text(lk, "clipindex", ci)
                n_clips += 1
            _text(track, "enabled", "TRUE")
            _text(track, "locked", "FALSE")
    for m in snap.markers:
        me = ET.SubElement(seq, "marker")
        _text(me, "comment", m.comment)
        _text(me, "name", m.name)
        _text(me, "in", _frames(m.start_ticks, fps))
        _text(me, "out", -1)
        if m.color:
            _text(me, "color", m.color)
    ET.indent(root, space="  ")
    body = ET.tostring(root, encoding="unicode")
    text = f'<?xml version="1.0" encoding="UTF-8"?>\n<!DOCTYPE xmeml>\n<!-- {GENERATOR_NOTE} -->\n{body}\n'
    return ReadbackXml(text, n_clips, sorted(set(not_carried)))


def crosscheck_summary(mismatches: list[Any], limit: int = 20) -> dict[str, Any]:
    """The read-back-versus-plan diff in the shape the handoff report prints."""
    return {"ok": not mismatches, "count": len(mismatches), "items": [str(m) for m in mismatches[:limit]]}


# ---- deciding and generating ------------------------------------------------------------------------------

REPORT_NAME = "readback_interchange.json"
XML_NAME = "timeline.xml"
NATIVE_KEPT_NAME = "timeline.native.xml"
CANDIDATE_NAME = "timeline.readback.xml"
LOSES = (
    "Generated from the FilmCraft read-back, not by FilmCraft's exporter: titles are media-less clip items carrying only their text (no font, size or position).",
    "Effects other than the Motion scale and constant clip gain are not written; keyframes (music ducking) are not written, because the read-back "
    "reports how many keyframes a parameter has, not their times and values.",
    "Only centred cross dissolves are written.",
)


def native_state(xml_path: Path, spec: Any, *, listed_error: str | None = None) -> tuple[str, list[str]]:
    """('ok' | 'missing' | 'unreadable' | 'lossy', details) for FilmCraft's own timeline.xml, judged the way the compatibility report judges it."""
    from trip_vlog.handoff import xml_roundtrip as X
    from trip_vlog.handoff.fcp7_xml import XmlReadError, parse_fcp7_xml

    if listed_error:
        return "missing", [listed_error]
    if not xml_path.is_file() or xml_path.stat().st_size == 0:
        return "missing", [f"{xml_path.name} was not written"]
    try:
        tl = parse_fcp7_xml(xml_path)
    except XmlReadError as e:
        return "unreadable", [str(e)]
    rt = X.compare_timeline_xml(tl, X.expected_from_spec(spec))
    if rt.ok:
        return "ok", []
    return "lossy", [str(m) for m in rt.mismatches[:10]] + ([f"... {len(rt.mismatches) - 10} more"] if len(rt.mismatches) > 10 else [])


def run_fallback(adapter: Any, spec: Any, requested: list[str], out_dir: Path, project_path: Path, *, mode: str,
                 listed_error: str | None = None) -> dict[str, Any]:
    """Decide whether the read-back fallback is needed and make it. Returns the provenance record (also written to ``readback_interchange.json``).

    A native export that checks out is never touched. A native export that is lossy is KEPT as ``timeline.native.xml`` when a generated file
    that round-trips exactly takes the name ``timeline.xml``; if the generated file does not round-trip it is discarded and the native file stays.
    """
    import hashlib
    import os

    from trip_vlog.filmcraft.inspect import verify_against_spec
    from trip_vlog.handoff import xml_roundtrip as X
    from trip_vlog.handoff.fcp7_xml import XmlReadError, parse_fcp7_xml
    from trip_vlog.logging_utils import utc_now_iso
    from trip_vlog.state import atomic_write_json, atomic_write_text

    rec_path = out_dir / REPORT_NAME

    def done(status: str, reason: str, **extra: Any) -> dict[str, Any]:
        rec = {"status": status, "reason": reason, "label": "generated from FilmCraft read-back" if status == "generated" else None, **extra}
        if status in ("generated", "failed"):
            rec["generated_at"] = utc_now_iso()
            atomic_write_json(rec_path, rec)
        elif rec_path.is_file():
            rec_path.replace(rec_path.with_name(rec_path.name + ".stale"))      # an earlier fallback no longer describes this folder
            stale = out_dir / NATIVE_KEPT_NAME
            if stale.is_file():
                stale.replace(stale.with_name(stale.name + ".stale"))
        return rec

    if mode == "off":
        return done("off", "filmcraft.readback_interchange is off")
    if "fcp7_xml" not in requested:
        return done("not_requested", "fcp7_xml is not among the requested interchange formats")
    native = out_dir / XML_NAME
    state, issues = native_state(native, spec, listed_error=listed_error)
    if state == "ok":
        return done("not_needed", "FilmCraft's own FCP7 XML export checks out against the timeline sent to FilmCraft", native={"state": state})
    base = {"native": {"state": state, "issues": issues}}
    try:
        adapter.close()
        snap, project = adapter.read_back(project_path)
        gen = build_readback_xml(snap, project)
    except Exception as e:  # noqa: BLE001 - FilmCraft, read-back and generator errors all end in a recorded failure
        return done("failed", f"the read-back timeline could not be turned into FCP7 XML: {type(e).__name__}: {e}", **base)
    cross = verify_against_spec(snap, spec, project=project)
    candidate = out_dir / CANDIDATE_NAME
    atomic_write_text(candidate, gen.text)
    try:
        rt = X.compare_timeline_xml(parse_fcp7_xml(candidate), X.expected_from_spec(spec), keyframes_carried=False)
    except XmlReadError as e:
        candidate.unlink(missing_ok=True)
        return done("failed", f"the generated file is not readable: {e}", **base, crosscheck=crosscheck_summary(cross.mismatches))
    if not rt.ok:
        candidate.unlink(missing_ok=True)
        return done("failed", f"the file generated from the read-back does not round-trip exactly against the expected timeline ({len(rt.mismatches)} mismatch(es)); "
                    "it was discarded", **base, crosscheck=crosscheck_summary(cross.mismatches), roundtrip=[str(m) for m in rt.mismatches[:10]])
    if state != "missing" and native.is_file():
        os.replace(native, out_dir / NATIVE_KEPT_NAME)
    os.replace(candidate, native)
    sha = hashlib.sha256(native.read_bytes()).hexdigest()
    return done("generated", f"FilmCraft's own FCP7 XML export is {state}; {XML_NAME} was generated from the timeline read back from FilmCraft after reopening the saved project",
                **base, file=XML_NAME, sha256=sha, kept_native=NATIVE_KEPT_NAME if state != "missing" else None, clips=gen.clips,
                not_carried=gen.not_carried, loses=list(LOSES), crosscheck=crosscheck_summary(cross.mismatches),
                roundtrip={"ok": True, "expected": dict(rt.expected), "matched": dict(rt.matched)})
